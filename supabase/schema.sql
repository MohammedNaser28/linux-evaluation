-- Reference schema for the `submissions` table used by the leaderboard.
-- The table already exists in your Supabase project (the qo2 CLI inserts into it).
-- Run these only if you're creating the table from scratch or adding columns.

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  student_id text not null,
  question_id text not null,
  flag text,
  created_at timestamptz not null default now()
);

create index if not exists submissions_student_idx on public.submissions (student_id);
create index if not exists submissions_question_idx on public.submissions (question_id);

-- Dry-run table for the test archive (test.enc). Test level keys (test1..test10)
-- are routed here so they never pollute the real leaderboard. The admin page
-- shows these in its "Test run" section.
create table if not exists public.test_submissions (
  id          bigint generated by default as identity primary key,
  student_id  text not null,
  question_id text not null,
  flag        text,
  created_at  timestamptz not null default now()
);

create index if not exists test_submissions_student_idx  on public.test_submissions (student_id);
create index if not exists test_submissions_question_idx on public.test_submissions (question_id);

-- Attendance: every `qo start` logs one row here so the /admin/logs page can
-- show which roster students entered and which didn't. source = eval|test.
create table if not exists public.session_logs (
  id         bigint generated by default as identity primary key,
  student_id text not null,
  source     text not null default 'eval',
  entered_at timestamptz not null default now()
);

create index if not exists session_logs_student_idx on public.session_logs (student_id);
create index if not exists session_logs_source_idx  on public.session_logs (source);

-- The sandbox authenticates with the publishable (anon) key. Grant the anon role
-- INSERT only; reads stay service-role only (server-side in this app).
create policy "sandbox inserts submissions"
  on public.submissions for insert to anon with check (true);

create policy "sandbox inserts test_submissions"
  on public.test_submissions for insert to anon with check (true);

create policy "sandbox inserts session_logs"
  on public.session_logs for insert to anon with check (true);

-- The qo2 sandbox writes rows via the service role (bypasses RLS), so no insert
-- policy is needed for the leaderboard. This app reads with the service role
-- key server-side only; the anon key is never used in the browser.

alter table public.submissions enable row level security;

